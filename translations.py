def normalize_language(value: str | None) -> str | None:
    """Normalize browser and query-string language tags to supported locales."""
    if not value:
        return None
    normalized = value.strip().lower().replace("_", "-")
    if normalized.startswith("zh"):
        return "zh-CN"
    if normalized.startswith("en"):
        return "en"
    return None


def translate(language: str, key: str, **values: Any) -> str:
    """Translate a message key, falling back to the English catalog."""
    locale = language if language in TRANSLATIONS else DEFAULT_LANGUAGE
    template = TRANSLATIONS[locale].get(key, TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key))
    return template.format(**values) if values else template
